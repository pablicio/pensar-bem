"""Os traços de cada dígito, numa caixa de 0 a 1."""
import numpy as np


def arco(cx, cy, rx, ry, de, ate, n=16):
    """Um pedaço de elipse, de `de` a `ate` graus."""
    a = np.radians(np.linspace(de, ate, n))
    return list(zip(cx + rx * np.cos(a), cy - ry * np.sin(a)))


